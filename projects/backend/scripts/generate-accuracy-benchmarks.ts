import { sql } from "drizzle-orm";
import { db } from "../src/db";

const REALM_ID = 1;

const result = await db.execute<{
  starBucket: number;
  scores: number;
  p50: number;
  p90: number;
  p99: number;
  p999: number;
}>(sql`
  SELECT floor(lr.stars)::int AS "starBucket", count(*)::int AS scores,
    round(percentile_cont(0.5) WITHIN GROUP (ORDER BY s.accuracy)::numeric, 2)::float AS p50,
    round(percentile_cont(0.9) WITHIN GROUP (ORDER BY s.accuracy)::numeric, 2)::float AS p90,
    round(percentile_cont(0.99) WITHIN GROUP (ORDER BY s.accuracy)::numeric, 2)::float AS p99,
    round(percentile_cont(0.999) WITHIN GROUP (ORDER BY s.accuracy)::numeric, 2)::float AS p999
  FROM "scoresaber-score-realms" sr
  JOIN "scoresaber-scores" s ON s."scoreId" = sr."scoreId"
  JOIN "scoresaber-leaderboard-realms" lr ON lr."leaderboardId" = sr."leaderboardId" AND lr."realmId" = sr."realmId"
  WHERE sr."realmId" = ${REALM_ID} AND sr.pp > 0 AND s.accuracy > 0
    AND sr."playerId" NOT IN (SELECT id FROM "scoresaber-accounts" WHERE banned = true)
  GROUP BY 1 ORDER BY 1
`);

const rows = result.rows.map(
  row =>
    `  { starBucket: ${row.starBucket}, scores: ${row.scores}, p50: ${row.p50}, p90: ${row.p90}, p99: ${row.p99}, p999: ${row.p999} },`
);
const output = `/**
 * Accuracy percentiles of every ranked ScoreSaber score by whole-star bucket, generated by
 * scripts/generate-accuracy-benchmarks.ts. Regenerate it when the ranked score pool changes a lot.
 */
export const ACCURACY_BENCHMARKS_AS_OF = "${new Date().toISOString().slice(0, 10)}";

export const ACCURACY_BENCHMARKS = [
${rows.join("\n")}
] satisfies AccuracyBenchmark[];

export type AccuracyBenchmark = {
  starBucket: number;
  scores: number;
  p50: number;
  p90: number;
  p99: number;
  p999: number;
};
`;
await Bun.write(new URL("../src/service/chat/tools/accuracy-benchmark-data.ts", import.meta.url), output);
console.log(`Wrote ${rows.length} buckets`);
process.exit(0);
